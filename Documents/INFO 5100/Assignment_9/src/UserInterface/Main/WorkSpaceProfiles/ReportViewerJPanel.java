    // shows the report picked in the dropdown
    private void showSelectedReport() {
        String report = (String) cmbReports.getSelectedItem();
        if (report.equals("Most Expensive Products")) {
            showMostExpensiveProducts();
        }
        if (report.equals("Most Valuable Customers")) {
            showMostValuableCustomers();
        }
        if (report.equals("Supplier Report")) {
            showSupplierReport();
        }

    }

    // a read-only table model that sorts numbers as numbers
    private DefaultTableModel newTableModel(String[] columns) {
        return new DefaultTableModel(columns, 0) {
            @Override
            public Class<?> getColumnClass(int column) {
                if (getRowCount() == 0) {
                    return Object.class;
                }
                return getValueAt(0, column).getClass();
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
    }

    // Report 1
    private void showMostExpensiveProducts() {
        DefaultTableModel model = newTableModel(new String[]{"Product", "Supplier", "Price"});
        for (Supplier supplier : business.getSupplierDirectory().getSuplierList()) {
            for (Product product : supplier.getProductCatalog().getProductList()) {
                Object[] row = new Object[3];
                row[0] = product.toString();
                row[1] = supplier.getName();
                row[2] = product.getTargetPrice();
                model.addRow(row);
            }
        }
        tblReport.setModel(model);

        // sort by price: first toggle = low to high, second = high to low
        tblReport.getRowSorter().toggleSortOrder(2);
        tblReport.getRowSorter().toggleSortOrder(2);
    }
    // Report 2: every customer with their total sales, highest first
    private void showMostValuableCustomers() {
        DefaultTableModel model = newTableModel(new String[]{"Customer", "Total Sales"});
        CustomersReport customersreport = business.getCustomerDirectory().generatCustomerPerformanceReport();
        for (CustomerSummary cs : customersreport.getCustomersSortedBySales()) {
            Object[] row = new Object[2];
            row[0] = cs.getCustomerName();
            row[1] = cs.getOrderTotal();
            model.addRow(row);
        }
        tblReport.setModel(model);
    }

    // Report 3: one row per supplier with sales, loyalty, average spending and top 5 score
    private void showSupplierReport() {
        DefaultTableModel model = newTableModel(new String[]{"Supplier", "Total Sales", "Loyalty Score", "Avg Spending / Customer", "Top 5 Sales Score"});
        SupplierReport supplierreport = business.generateSupplierReport();
        for (SupplierSummary ss : supplierreport.getSuppliersSortedBySales()) {
            Object[] row = new Object[5];
            row[0] = ss.getSupplierName();
            row[1] = ss.getTotalSales();
            row[2] = Math.round(ss.getLoyaltyScore() * 100) / 100.0;     // 2 decimals
            row[3] = ss.getAverageSpending();
            row[4] = Math.round(ss.getTop5SalesScore() * 100) / 100.0;   // 2 decimals
            model.addRow(row);
        }
        tblReport.setModel(model);
    
        
    }


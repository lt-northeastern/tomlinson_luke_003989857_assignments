    private void refreshTextFields() {
        Person p = useraccount.getProfile().getPerson();
        EmployeeProfile ep = (EmployeeProfile) useraccount.getProfile();

        txtName.setText(p.getFirstName() + " " + p.getLastName());
        txtUsername.setText(useraccount.getUserLoginName());
        txtRole.setText(useraccount.getRole());
        txtEmail.setText(ep.getEmail());
        txtPhone.setText(ep.getPhone());
        txtDepartment.setText(ep.getDepartment());
        txtTitle.setText(ep.getTitle());
    }


    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
                String role = (String) cmbRoles.getSelectedItem();
        String nuid = txtNUID.getText().trim();
        String un = txtUsername.getText().trim();
        String pw = txtPassword.getText().trim();

        if (nuid.isEmpty() || un.isEmpty() || pw.isEmpty()) {
            JOptionPane.showMessageDialog(this, "NUID, username, and password are required.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Person person = business.getPersonDirectory().findPerson(nuid);
        if (person == null) {
            JOptionPane.showMessageDialog(this, "This NUID is not registered. Add it in Register Persons (HR) first.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (business.getUserAccountDirectory().findByUsername(un) != null) {
            JOptionPane.showMessageDialog(this, "Username already taken.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Profile profile;
        if (role.equals("Student")) {
            profile = business.getStudentDirectory().newStudentProfile(person);
        } else if (role.equals("Faculty")) {
            profile = business.getFacultyDirectory().newFacultyProfile(person);
        } else {
            EmployeeProfile ep = business.getEmployeeDirectory().newEmployeeProfile(person);
            ep.setEmail(txtEmail.getText().trim());
            ep.setPhone(txtPhone.getText().trim());
            ep.setDepartment(txtDepartment.getText().trim());
            ep.setTitle(txtTitle.getText().trim());
            profile = ep;
        }

        business.getUserAccountDirectory().newUserAccount(profile, un, pw);

        JOptionPane.showMessageDialog(this, role + " account created.", "Success", JOptionPane.INFORMATION_MESSAGE);

        txtNUID.setText("");
        txtUsername.setText("");
        txtPassword.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtDepartment.setText("");
        txtTitle.setText("");
    }//GEN-LAST:event_btnCreateActionPerformed


